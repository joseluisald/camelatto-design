// Builds an isolated fixture; never changes database content or the active site.
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import assert from 'node:assert/strict';
import { buildFront } from '../src/lib/build-front';
import { joinBase, siteConfig } from '../../site.config.mjs';

const workspace = path.resolve('..');
const readJson = async (file: string) => JSON.parse(await readFile(path.join(workspace, 'src/data', file), 'utf8'));
const portfolio = await readJson('portfolio.json');
const settings = (await readJson('settings.json')).site;
const faq = await readJson('faq.json');
const token = randomUUID();
const marker = `CONTEUDO DO ADMIN ${token}`;
settings.title = `SEO ADMIN ${token}`;
portfolio.hero.title = marker;
portfolio.approach.steps[0].title = `METODO ADMIN ${token}`;
portfolio.projects = [{ ...portfolio.projects[0], id: `project-${token}`, displayId: '01', slug: `integracao-${token}`, title: `PROJETO ADMIN ${token}`, featured: 1 }];
portfolio.contact.description = `CONTATO ADMIN ${token}`;
faq[0].question = `FAQ ADMIN ${token}`;
const snapshot = { schemaVersion: 1, settings, portfolio, faq, redirects: [] };
const { output } = await buildFront({ snapshot, id: `contract-${token}`, workspace, stagingRoot: path.join(workspace, '.publish') });
const html = await readFile(path.join(output, 'index.html'), 'utf8');
assert.ok(html.includes(marker), 'Hero must consume the admin snapshot');
assert.ok(html.includes(settings.title), 'Global SEO must consume the admin snapshot');
assert.ok(html.includes(portfolio.approach.steps[0].title), 'Project stages must consume the admin snapshot');
assert.ok(html.includes(portfolio.contact.description), 'Contact must consume the admin snapshot');
assert.ok(html.includes(faq[0].question), 'FAQ must consume the admin snapshot');
assert.ok(html.includes(joinBase(siteConfig.base, 'admin/api/public/leads')), 'Lead endpoint must include the deployment base');
const project = await readFile(path.join(output, 'projetos', portfolio.projects[0].slug, 'index.html'), 'utf8');
assert.ok(project.includes(portfolio.projects[0].title), 'A new project slug must produce its own case study');
assert.ok(project.includes(joinBase(siteConfig.base, '#projetos')), 'The back link must include the deployment base');
console.log('Front integrado validado: SEO, hero, etapas, contato, FAQ, novo estudo de caso e API de leads com base. Build de teste isolado, sem alterar o site ativo.');
